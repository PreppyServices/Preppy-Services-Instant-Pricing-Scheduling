export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const template = COPY[lang]?.[key] ?? COPY.en[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value)),
    template
  );
}

export function durationLabel(lang: Lang, minutes: number): string {
  const hours = Math.max(1, Math.round(minutes / 60));
  if (hours === 1) return t(lang, "about1");
  return t(lang, "aboutN", { n: hours });
}

export function normalizeLang(raw: string): Lang {
  const value = raw.toLowerCase().slice(0, 2);
  if (value === "es" || value === "fr") return value;
  return "en";
}

/** Null fields render nothing. Flags default off. */
export function featureLines(flags: FeatureFlags, lang: Lang) {
  return {
    packages: flags.packages ? t(lang, "packages") : null,
    gift: flags.gift ? t(lang, "gift") : null,
    holiday: flags.holidayPromo ? t(lang, "holiday") : null,
    showNoCharge: !flags.deposit,
  };
}
